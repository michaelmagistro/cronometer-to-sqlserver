-- Real-world scenario: FriendIDs stored as comma-separated string
-- We need to "explode" that string into separate rows

CREATE TABLE #Friends (
	CustomerID INT,
	CustomerName VARCHAR(50),
	FriendIDs VARCHAR(100)  -- Stored as "1,2,3,4"
);

CREATE TABLE #Addresses (
	CustomerID INT,
	Address VARCHAR(100),
	priority INT
);

