-- "This is where CROSS APPLY really shines - nested relationships" << Really? We just did a simple join before??
-- no, THIS is where CROSS APPLY really shines: the ability to join a table but 
SELECT 
	f.CustomerName AS Customer,
	f2.CustomerName AS FriendName,
	addr.Address AS FriendAddress
FROM #Friends f
CROSS APPLY STRING_SPLIT(f.FriendIDs, ',') AS theSplitTbl
JOIN #Friends f2 ON f2.CustomerID = CAST(theSplitTbl.value AS INT)
CROSS APPLY (
	SELECT Address
	FROM #Addresses
	WHERE CustomerID = f2.CustomerID
) addr; -- a new join with the potential to be tailored. 

