-- NO -- THIS is where CROSS APPLY really shines - a way to have a >>>tailored JOIN<<< utilizing TOP and ORDER BY.
SELECT 
	f.CustomerName AS Customer,
	friend.CustomerName AS FriendName,
	addr.Address AS FriendAddress
FROM #Friends f
CROSS APPLY STRING_SPLIT(f.FriendIDs, ',') AS theSplitTbl
JOIN #Friends friend ON friend.CustomerID = CAST(theSplitTbl.value AS INT)
CROSS APPLY (
	SELECT TOP 1 Address -- toggle between top 1 and top 2 to see how we can tailor the join.
	FROM #Addresses a
	WHERE CustomerID = friend.CustomerID
	ORDER BY a.priority DESC
) addr;

-- Notice: Carol has two addresses. If TOP 2 then she appears TWICE, if TOP 1, then she appears ONCE
